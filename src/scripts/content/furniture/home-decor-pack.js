function decor(id, name, livingClass, tags, options = {}) {
  const tier = livingClasses[livingClass];
  const adjustment = decorAdjustments[id] ?? {};
  const width = options.width ?? 1;
  const height = options.height ?? 1;
  window.DungeonContent.register("furniture", id, {
    name,
    kind: "feature",
    tags: ["furniture", "decor", "home-decor", "living-accommodation", livingClass, ...tags, ...(floorLevelDecor.has(id) || options.floor ? ["floor"] : [])],
    width,
    height,
    blocksMovement: options.blocksMovement ?? !walkableSoftDecor.has(id),
    blocksLineOfSight: Boolean(options.blocksLineOfSight),
    inspectable: true,
    interactable: true,
    symbol: options.symbol ?? tier.symbol,
    weight: options.weight ?? (width > 1 || height > 1 ? 666 : undefined),
    spawnChance: options.spawnChance ?? 0.02,
    placement: options.placement ?? "random-room-cell",
    description: options.description,
    components: [
      {
        type: "homeDecor",
        livingClass,
        livingClassLabel: tier.label,
        priceCp: adjustment.priceCp ?? tier.priceCp,
        comfort: adjustment.comfort ?? tier.comfort,
      },
      ...(options.components ?? []),
    ],
  });
}

